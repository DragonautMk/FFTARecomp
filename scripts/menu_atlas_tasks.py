#!/usr/bin/env python3
"""Keep the read-only native Atlas V2 reference aligned with the task checklist."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/development/DEBUG_TOOLS_V2_TODO.md'
DEST = ROOT / 'crates/menu/assets/debug_v2.tsv'

def render():
    text = SOURCE.read_text()
    matches = list(re.finditer(r'^- \[([ x])\] \*\*(DBG2-(\d{2})) — (.+?)\.\*\*', text, re.M))
    assert [int(m[3]) for m in matches] == list(range(1, 29))
    lines = ['# Generated by scripts/menu_atlas_tasks.py; reference only, no dispatch.']
    for i, m in enumerate(matches):
        n = int(m[3])
        group = 1 if n <= 7 else 4 if n <= 12 else 5 if n <= 16 else 6 if n <= 23 else 3 if n <= 25 else 7
        body = text[m.end():matches[i+1].start() if i+1 < len(matches) else len(text)]
        body = re.split(r'^## ', body, maxsplit=1, flags=re.M)[0]
        body = ' '.join(body.replace('**', '').replace('`', '').split())
        lines.append('\t'.join([m[2], str(group), str(m[1] == 'x').lower(), m[4], body]))
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    args = argparse.ArgumentParser()
    args.add_argument('--check', action='store_true')
    opts = args.parse_args()
    result = render()
    if opts.check:
        assert DEST.read_text() == result, 'Atlas task reference is stale; run scripts/menu_atlas_tasks.py'
        print('Atlas: 28 task references match the current checklist')
    else:
        DEST.write_text(result)
